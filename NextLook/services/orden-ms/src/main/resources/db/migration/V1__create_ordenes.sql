CREATE TABLE IF NOT EXISTS ordenes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    keycloak_id VARCHAR(36) NOT NULL,
    id_cliente BIGINT,
    nombre_cliente VARCHAR(170),
    direccion_envio VARCHAR(500),
    estado VARCHAR(20) NOT NULL,
    metodo_pago VARCHAR(20) NOT NULL,
    total NUMERIC(10,2) NOT NULL DEFAULT 0,
    observacion VARCHAR(300),
    fecha_creacion TIMESTAMP NOT NULL DEFAULT now(),
    fecha_actualizacion TIMESTAMP NOT NULL DEFAULT now(),
    PRIMARY KEY (id),
    CONSTRAINT ck_ordenes_estado CHECK (estado IN ('CARRITO','PENDIENTE_STOCK','PENDIENTE_PAGO','PAGADA','CANCELADA')),
    CONSTRAINT ck_ordenes_metodo CHECK (metodo_pago IN ('TARJETA','YAPE','PLIN'))
);
CREATE INDEX IF NOT EXISTS ix_ordenes_keycloak ON ordenes(keycloak_id);

-- Copia historica de la prenda al momento de la compra (precio, talla y color no cambian despues).
CREATE TABLE IF NOT EXISTS orden_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_orden BIGINT NOT NULL REFERENCES ordenes(id) ON DELETE CASCADE,
    variante_id BIGINT NOT NULL,
    prenda_id BIGINT,
    nombre_prenda VARCHAR(120),
    talla VARCHAR(10),
    color VARCHAR(30),
    precio_unitario NUMERIC(10,2),
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    PRIMARY KEY (id),
    CONSTRAINT uk_orden_items_variante UNIQUE (id_orden, variante_id)
);
