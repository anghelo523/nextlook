-- keycloak_id es el "sub" del JWT de Keycloak: une al usuario autenticado con su perfil.
CREATE TABLE IF NOT EXISTS clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    keycloak_id VARCHAR(36) NOT NULL,
    nombres VARCHAR(80) NOT NULL,
    apellidos VARCHAR(80) NOT NULL,
    email VARCHAR(150) NOT NULL,
    dni VARCHAR(8),
    telefono VARCHAR(20),
    fecha_registro TIMESTAMP NOT NULL DEFAULT now(),
    PRIMARY KEY (id),
    CONSTRAINT uk_clientes_keycloak UNIQUE (keycloak_id),
    CONSTRAINT uk_clientes_email UNIQUE (email),
    CONSTRAINT uk_clientes_dni UNIQUE (dni)
);

CREATE TABLE IF NOT EXISTS direcciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_cliente BIGINT NOT NULL REFERENCES clientes(id) ON DELETE CASCADE,
    alias VARCHAR(40) NOT NULL,
    direccion VARCHAR(200) NOT NULL,
    distrito VARCHAR(80) NOT NULL,
    ciudad VARCHAR(80) NOT NULL,
    referencia VARCHAR(200),
    principal BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (id)
);
