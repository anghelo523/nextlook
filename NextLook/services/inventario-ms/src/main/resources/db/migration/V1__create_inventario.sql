-- Stock por variante (prenda + talla + color). variante_id es el id de catalogo-ms.
CREATE TABLE IF NOT EXISTS stock_variante (
    variante_id BIGINT NOT NULL,
    sku VARCHAR(40) NOT NULL,
    disponible INTEGER NOT NULL CHECK (disponible >= 0),
    reservado INTEGER NOT NULL DEFAULT 0 CHECK (reservado >= 0),
    fecha_actualizacion TIMESTAMP NOT NULL DEFAULT now(),
    PRIMARY KEY (variante_id),
    CONSTRAINT uk_stock_sku UNIQUE (sku)
);

-- S09: una fila por orden procesada. Es la "memoria" del consumidor idempotente:
-- si orden.creada llega dos veces, el UNIQUE impide procesarla de nuevo.
CREATE TABLE IF NOT EXISTS orden_procesada (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    orden_id BIGINT NOT NULL,
    resultado VARCHAR(20) NOT NULL,
    motivo VARCHAR(300),
    fecha TIMESTAMP NOT NULL DEFAULT now(),
    PRIMARY KEY (id),
    CONSTRAINT uk_orden_procesada UNIQUE (orden_id),
    CONSTRAINT ck_orden_procesada_resultado CHECK (resultado IN ('RESERVADO','RECHAZADO'))
);

CREATE TABLE IF NOT EXISTS reserva_stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    orden_id BIGINT NOT NULL,
    variante_id BIGINT NOT NULL REFERENCES stock_variante(variante_id),
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    estado VARCHAR(20) NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT now(),
    fecha_actualizacion TIMESTAMP NOT NULL DEFAULT now(),
    PRIMARY KEY (id),
    CONSTRAINT uk_reserva_orden_variante UNIQUE (orden_id, variante_id),
    CONSTRAINT ck_reserva_estado CHECK (estado IN ('RESERVADA','CONFIRMADA','LIBERADA'))
);
CREATE INDEX IF NOT EXISTS ix_reserva_orden ON reserva_stock(orden_id);
