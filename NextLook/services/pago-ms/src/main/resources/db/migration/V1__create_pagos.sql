CREATE TABLE IF NOT EXISTS pagos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    orden_id BIGINT NOT NULL,
    keycloak_id VARCHAR(36) NOT NULL,
    id_cliente BIGINT,
    monto NUMERIC(10,2) NOT NULL,
    metodo_pago VARCHAR(20) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    titular VARCHAR(80),
    id_transaccion VARCHAR(60),
    motivo VARCHAR(300),
    fecha_creacion TIMESTAMP NOT NULL DEFAULT now(),
    fecha_actualizacion TIMESTAMP NOT NULL DEFAULT now(),
    PRIMARY KEY (id),
    -- S09: un solo pago por orden aunque orden.creada llegue dos veces.
    CONSTRAINT uk_pagos_orden UNIQUE (orden_id),
    CONSTRAINT ck_pagos_estado CHECK (estado IN ('PENDIENTE','LISTO_PARA_PAGAR','APROBADO','RECHAZADO','ANULADO'))
);
CREATE INDEX IF NOT EXISTS ix_pagos_keycloak ON pagos(keycloak_id);
