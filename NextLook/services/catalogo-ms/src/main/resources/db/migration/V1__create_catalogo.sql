CREATE TABLE IF NOT EXISTS categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(80) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_categorias_nombre UNIQUE (nombre)
);

CREATE TABLE IF NOT EXISTS prendas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(120) NOT NULL,
    descripcion VARCHAR(255),
    marca VARCHAR(80),
    genero VARCHAR(10) NOT NULL,
    precio NUMERIC(10, 2) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    id_categoria BIGINT NOT NULL REFERENCES categorias(id),
    PRIMARY KEY (id)
);

-- Cada combinacion talla/color de una prenda es una variante con su propio SKU.
-- El stock de cada variante NO vive aqui: es de inventario-ms (base de datos propia).
CREATE TABLE IF NOT EXISTS variantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_prenda BIGINT NOT NULL REFERENCES prendas(id),
    talla VARCHAR(10) NOT NULL,
    color VARCHAR(40) NOT NULL,
    sku VARCHAR(40) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id),
    CONSTRAINT uk_variantes_sku UNIQUE (sku),
    CONSTRAINT uk_variantes_prenda_talla_color UNIQUE (id_prenda, talla, color)
);
